-- Esquema PostgreSQL do controle de presença (equivalente a src/domain/types.ts).
--
-- O comando "npm run db:setup" cria o banco, executa este arquivo e insere os
-- dados de demonstração. Para executá-lo manualmente:
--
--   createdb -U postgres presenca
--   psql -U postgres -d presenca -f database/schema.sql
--
-- O arquivo pode ser executado mais de uma vez: só cria o que ainda não existe.
--
-- Minimização de dados (LGPD): são guardados apenas os dados necessários ao
-- controle de frequência. A localização do aluno é gravada somente no momento
-- do registro da presença; não há rastreamento contínuo.

-- ---------------------------------------------------------------------------
-- Cadastros
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS professores (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        TEXT NOT NULL CHECK (BTRIM(nome) <> ''),
    email       TEXT NOT NULL CHECK (BTRIM(email) <> ''),
    senha_hash  TEXT NOT NULL,
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS professores_email_unico ON professores (LOWER(email));

CREATE TABLE IF NOT EXISTS alunos (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        TEXT NOT NULL CHECK (BTRIM(nome) <> ''),
    matricula   TEXT NOT NULL CHECK (BTRIM(matricula) <> ''),
    email       TEXT NOT NULL CHECK (BTRIM(email) <> ''),
    senha_hash  TEXT NOT NULL,
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS alunos_matricula_unica ON alunos (matricula);
CREATE UNIQUE INDEX IF NOT EXISTS alunos_email_unico ON alunos (LOWER(email));

CREATE TABLE IF NOT EXISTS turmas (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RESTRICT: um professor com turmas não pode ser excluído
    professor_id  INTEGER NOT NULL REFERENCES professores (id) ON DELETE RESTRICT,
    codigo        TEXT NOT NULL CHECK (BTRIM(codigo) <> ''),
    nome          TEXT NOT NULL CHECK (BTRIM(nome) <> ''),
    disciplina    TEXT NOT NULL CHECK (BTRIM(disciplina) <> ''),
    semestre      TEXT NOT NULL CHECK (BTRIM(semestre) <> ''),
    local         TEXT NOT NULL,
    -- ponto de referência da sala, salvo na última chamada da turma
    latitude      DOUBLE PRECISION CHECK (latitude BETWEEN -90 AND 90),
    longitude     DOUBLE PRECISION CHECK (longitude BETWEEN -180 AND 180),
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS turmas_codigo_semestre_unico ON turmas (codigo, semestre);
CREATE INDEX IF NOT EXISTS turmas_professor ON turmas (professor_id);

CREATE TABLE IF NOT EXISTS matriculas (
    turma_id  INTEGER NOT NULL REFERENCES turmas (id) ON DELETE CASCADE,
    aluno_id  INTEGER NOT NULL REFERENCES alunos (id) ON DELETE CASCADE,
    PRIMARY KEY (turma_id, aluno_id)
);
CREATE INDEX IF NOT EXISTS matriculas_aluno ON matriculas (aluno_id);

-- ---------------------------------------------------------------------------
-- Chamadas e presenças
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS chamadas (
    id            UUID PRIMARY KEY,
    -- RESTRICT: uma turma com chamadas não pode ser excluída
    turma_id      INTEGER NOT NULL REFERENCES turmas (id) ON DELETE RESTRICT,
    professor_id  INTEGER NOT NULL REFERENCES professores (id) ON DELETE RESTRICT,
    iniciada_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    encerrada_em  TIMESTAMPTZ CHECK (encerrada_em >= iniciada_em),
    -- coordenada de referência do local da aula
    latitude      DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude     DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    raio_metros   INTEGER NOT NULL DEFAULT 20 CHECK (raio_metros > 0)
);
CREATE INDEX IF NOT EXISTS chamadas_turma ON chamadas (turma_id, iniciada_em DESC);
CREATE INDEX IF NOT EXISTS chamadas_professor ON chamadas (professor_id, iniciada_em DESC);
-- cada professor só pode ter uma chamada aberta (ErroDeDuplicidade em ChamadaRepository.criar)
CREATE UNIQUE INDEX IF NOT EXISTS chamadas_uma_aberta_por_professor
    ON chamadas (professor_id) WHERE encerrada_em IS NULL;

CREATE TABLE IF NOT EXISTS presencas (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamada_id        UUID NOT NULL REFERENCES chamadas (id) ON DELETE CASCADE,
    -- RESTRICT: um aluno com presenças registradas não pode ser excluído
    aluno_id          INTEGER NOT NULL REFERENCES alunos (id) ON DELETE RESTRICT,
    registrada_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    origem            TEXT NOT NULL CHECK (origem IN ('QR_CODE', 'MANUAL')),
    -- coordenada enviada pelo aluno somente no momento do registro (nula no registro manual)
    latitude          DOUBLE PRECISION CHECK (latitude BETWEEN -90 AND 90),
    longitude         DOUBLE PRECISION CHECK (longitude BETWEEN -180 AND 180),
    distancia_metros  INTEGER CHECK (distancia_metros >= 0),
    CHECK (origem = 'MANUAL' OR (latitude IS NOT NULL AND longitude IS NOT NULL))
);
-- impede presença duplicada (ErroDeDuplicidade em PresencaRepository.criar)
CREATE UNIQUE INDEX IF NOT EXISTS presencas_uma_por_aluno_na_chamada ON presencas (chamada_id, aluno_id);
CREATE INDEX IF NOT EXISTS presencas_aluno ON presencas (aluno_id);

-- As faltas não são gravadas: um aluno matriculado sem linha em "presencas"
-- está AUSENTE (chamada encerrada) ou PENDENTE (chamada aberta). A visão
-- vw_registros_presenca, abaixo, mostra esse resultado linha a linha.

-- ---------------------------------------------------------------------------
-- Tentativas de registro pelo aplicativo
-- ---------------------------------------------------------------------------

-- Resultado de cada leitura de QR Code enviada pelo aluno, aceita ou recusada.
-- Serve para os indicadores da avaliação do protótipo (percentual de sucesso,
-- falhas por motivo). Por minimização de dados, a coordenada do aluno NÃO é
-- guardada aqui: apenas a distância calculada, quando houver.
CREATE TABLE IF NOT EXISTS tentativas_registro (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id          INTEGER NOT NULL REFERENCES alunos (id) ON DELETE CASCADE,
    -- nula quando o QR Code não corresponde a nenhuma chamada
    chamada_id        UUID REFERENCES chamadas (id) ON DELETE CASCADE,
    resultado         TEXT NOT NULL CHECK (resultado IN (
                          'REGISTRADA', 'QR_INVALIDO', 'QR_EXPIRADO', 'CHAMADA_ENCERRADA',
                          'SEM_PERMISSAO', 'PRESENCA_DUPLICADA', 'COORDENADAS_INVALIDAS', 'FORA_DO_RAIO')),
    distancia_metros  INTEGER CHECK (distancia_metros >= 0),
    tentada_em        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS tentativas_chamada ON tentativas_registro (chamada_id);
CREATE INDEX IF NOT EXISTS tentativas_aluno ON tentativas_registro (aluno_id, tentada_em DESC);

-- ---------------------------------------------------------------------------
-- Visões para consultas e relatórios (pgAdmin, psql, exportações)
-- ---------------------------------------------------------------------------

-- Uma linha por aluno matriculado em cada chamada, com a situação calculada.
CREATE OR REPLACE VIEW vw_registros_presenca AS
SELECT
    c.id                    AS chamada_id,
    t.id                    AS turma_id,
    t.codigo                AS turma_codigo,
    t.disciplina,
    c.professor_id,
    a.id                    AS aluno_id,
    a.nome                  AS aluno_nome,
    a.matricula,
    c.iniciada_em           AS data_aula,
    p.registrada_em,
    p.origem,
    p.distancia_metros,
    CASE
        WHEN p.id IS NOT NULL       THEN 'PRESENTE'
        WHEN c.encerrada_em IS NULL THEN 'PENDENTE'
        ELSE 'AUSENTE'
    END                     AS status
FROM chamadas c
JOIN turmas t          ON t.id = c.turma_id
JOIN matriculas m      ON m.turma_id = c.turma_id
JOIN alunos a          ON a.id = m.aluno_id
LEFT JOIN presencas p  ON p.chamada_id = c.id AND p.aluno_id = a.id;

-- Frequência de cada aluno em cada turma, considerando as chamadas encerradas.
-- "abaixo_do_minimo" indica frequência inferior aos 75% exigidos (Parecer CNE/CES 224/2006).
CREATE OR REPLACE VIEW vw_frequencia_alunos AS
SELECT
    t.id                                            AS turma_id,
    t.codigo                                        AS turma_codigo,
    t.disciplina,
    a.id                                            AS aluno_id,
    a.nome                                          AS aluno_nome,
    a.matricula,
    COUNT(c.id)::INTEGER                            AS total_aulas,
    COUNT(p.id)::INTEGER                            AS presencas,
    (COUNT(c.id) - COUNT(p.id))::INTEGER            AS faltas,
    COALESCE(ROUND(100.0 * COUNT(p.id) / NULLIF(COUNT(c.id), 0)), 0)::INTEGER AS percentual_presenca,
    CASE WHEN COUNT(c.id) = 0 THEN FALSE
         ELSE 100.0 * COUNT(p.id) / COUNT(c.id) < 75 END AS abaixo_do_minimo
FROM turmas t
JOIN matriculas m      ON m.turma_id = t.id
JOIN alunos a          ON a.id = m.aluno_id
LEFT JOIN chamadas c   ON c.turma_id = t.id AND c.encerrada_em IS NOT NULL
LEFT JOIN presencas p  ON p.chamada_id = c.id AND p.aluno_id = a.id
GROUP BY t.id, t.codigo, t.disciplina, a.id, a.nome, a.matricula;

-- Quantidade de tentativas de registro por chamada e resultado.
CREATE OR REPLACE VIEW vw_tentativas_por_resultado AS
SELECT
    c.id            AS chamada_id,
    c.turma_id,
    c.professor_id,
    tr.resultado,
    COUNT(*)::INTEGER AS quantidade
FROM tentativas_registro tr
JOIN chamadas c ON c.id = tr.chamada_id
GROUP BY c.id, c.turma_id, c.professor_id, tr.resultado;
